export interface RailwayZoneMaster {
  zone_code: string;
  zone_name: string;
  headquarters: string;
  divisions: string[];
  active: boolean;
  source: string;
  source_type: 'OFFICIAL' | 'ZONE_DATA' | 'RAILWAY_DOCUMENT';
}

export interface RailwayDivisionMaster {
  division_code: string;
  division_name: string;
  zone_code: string;
  headquarters: string;
  active: boolean;
}

export interface MasterStation {
  id: string;
  station_code: string;
  station_name: string;
  official_name: string;
  short_name: string;
  zone_code: string;
  division_code: string;
  state: string;
  district: string;
  city: string;
  latitude: number;
  longitude: number;
  station_category: 'NSG-1' | 'NSG-2' | 'NSG-3' | 'NSG-4' | 'SG-1' | 'HG-1';
  numberOfPlatforms: number;
  is_junction: boolean;
  is_terminal: boolean;
  is_interchange: boolean;
  active: boolean;
  source: string;
  source_type: 'OFFICIAL' | 'ZONE_DATA' | 'RAILWAY_DOCUMENT' | 'COMMUNITY';
  last_verified_at: string;
  confidence: 'HIGH' | 'MEDIUM' | 'COMMUNITY';
}

export interface StationAlias {
  station_code: string;
  alias: string;
  language: string;
  normalized_alias: string;
}

export interface StationPlatformMaster {
  id: string;
  station_code: string;
  platform_number: string;
  platform_name: string;
  platform_type: 'ISLAND' | 'SIDE' | 'PASSENGER';
  is_active: boolean;
  last_verified_at: string;
  source: string;
  verification_status: 'VERIFIED' | 'COMMUNITY_APPROVED' | 'USER_REPORTED';
}

export interface RailwayLineMaster {
  line_code: string;
  line_name: string;
  zone_code: string;
  gauge: 'BROAD_GAUGE' | 'STANDARD_GAUGE' | 'METER_GAUGE';
  electrification: string;
  active: boolean;
}

export interface RouteSectionMaster {
  id: string;
  line_code: string;
  from_station_code: string;
  to_station_code: string;
  distance_km: number;
  sequence_order: number;
  direction: 'BOTH' | 'UP' | 'DOWN';
  track_count: number;
  electrification: string;
  active: boolean;
}

export interface RailwayRouteMaster {
  route_code: string;
  route_name: string;
  origin_station_code: string;
  dest_station_code: string;
  total_distance_km: number;
  direction: 'DOWN' | 'UP';
  active: boolean;
  stations: Array<{
    sequence_order: number;
    station_code: string;
    station_name: string;
    km_from_origin: number;
    distance_from_previous_km: number;
    distance_to_next_km: number;
    is_junction: boolean;
  }>;
}

